"""Generates the launcher icon layers: the Kept Promise mark with its tick cut out of the geometry.

VectorDrawable has no masks, so the cut is computed here (shapely) and written as plain fills.
Run from android/: python3 tools/icon_paths.py
"""
import math
from shapely.geometry import Polygon, LineString
from shapely.affinity import affine_transform

S, R, TX, TY = 60 / math.sqrt(2), 30, 50, 100
TICK = [(28, 56), (44, 72), (74, 38)]
TICK_W = 9.5


def half(side):
    # Lobe centre and the arc from the outer corner to the top cusp, sampled finely.
    sgn = -1 if side == 'l' else 1
    corner = (TX + sgn * S, TY - S)
    top = (TX, TY - 2 * S)
    cx, cy = (corner[0] + top[0]) / 2, (corner[1] + top[1]) / 2
    a0 = math.atan2(corner[1] - cy, corner[0] - cx)
    # Of the two semicircles between the corner and the cusp, keep the one bulging away from the seam.
    def arc(direction):
        return [(cx + R * math.cos(a0 + direction * math.pi * i / 96), cy + R * math.sin(a0 + direction * math.pi * i / 96)) for i in range(97)]
    arc = max((arc(1), arc(-1)), key=lambda pts: abs(pts[48][0] - TX))
    return Polygon([(TX, TY), *arc])


def cut(poly):
    return poly.difference(LineString(TICK).buffer(TICK_W / 2, cap_style='round', join_style='round', resolution=24))


def path_data(geom, m):
    geom = affine_transform(geom, m)
    polys = [geom] if geom.geom_type == 'Polygon' else list(geom.geoms)
    out = []
    for p in polys:
        for ring in [p.exterior, *p.interiors]:
            pts = list(ring.coords)
            out.append('M' + ' L'.join(f'{x:.2f},{y:.2f}' for x, y in pts[:-1]) + ' Z')
    return ' '.join(out)


# Foreground: 108dp canvas, mark at 54% inside the 66dp safe zone (same placement as logo/final.js).
k = 0.54
M = [k, 0, 0, k, 26, 27.5 - 4.4 * k]
L, Rr = cut(half('l')), cut(half('r'))

def vector(body):
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/icon_paths.py: the Kept Promise mark, tick cut out. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" '
            f'android:viewportWidth="108" android:viewportHeight="108">\n{body}</vector>\n')

res = '/home/user/2gether/android/app/src/main/res/'
open(res + 'drawable/ic_launcher_foreground.xml', 'w').write(vector(
    f'  <path android:fillColor="#FFFFFF" android:pathData="{path_data(L, M)}"/>\n'
    f'  <path android:fillColor="#A9B1F2" android:pathData="{path_data(Rr, M)}"/>\n'))
open(res + 'drawable/ic_launcher_monochrome.xml', 'w').write(vector(
    f'  <path android:fillColor="#FF000000" android:pathData="{path_data(L, M)}"/>\n'
    f'  <path android:fillColor="#8C000000" android:pathData="{path_data(Rr, M)}"/>\n'))
open(res + 'drawable/ic_launcher_background.xml', 'w').write(
    '<?xml version="1.0" encoding="utf-8"?>\n<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt" '
    'android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
    '  <path android:pathData="M0,0h108v108h-108z">\n    <aapt:attr name="android:fillColor">\n'
    '      <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="38" android:endY="108">\n'
    '        <item android:offset="0" android:color="#FF2C3474"/>\n        <item android:offset="1" android:color="#FF1A1F4D"/>\n'
    '      </gradient>\n    </aapt:attr>\n  </path>\n</vector>\n')
print('icon layers written')
